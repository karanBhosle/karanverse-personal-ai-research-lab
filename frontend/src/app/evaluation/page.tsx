"use client";

import { useState } from "react";

type EvalReport = {
  dataset_name: string;
  strategies: Array<{
    strategy: string;
    mrr_mean: number;
    ndcg_at_k: Record<string, number>;
    latency_ms_mean: number;
  }>;
};

export default function EvaluationPage() {
  const [report, setReport] = useState<EvalReport | null>(null);
  const [error, setError] = useState<string>();

  const onFile = async (file: File | null) => {
    if (!file) return;
    setError(undefined);
    try {
      const text = await file.text();
      setReport(JSON.parse(text) as EvalReport);
    } catch {
      setError("Invalid report.json file");
      setReport(null);
    }
  };

  const ranked = report?.strategies
    ? [...report.strategies].sort((a, b) => (b.ndcg_at_k["10"] ?? 0) - (a.ndcg_at_k["10"] ?? 0))
    : [];

  return (
    <div className="flex h-full flex-col overflow-y-auto">
      <header className="border-b border-zinc-800 px-6 py-5">
        <h1 className="text-2xl font-semibold">Evaluation</h1>
        <p className="text-sm text-zinc-500">
          View retrieval benchmark reports generated by{" "}
          <code className="text-zinc-400">scripts/run_retrieval_eval.py</code>.
        </p>
      </header>

      <div className="space-y-4 p-6">
        <label className="inline-flex cursor-pointer items-center gap-2 rounded-lg border border-zinc-700 px-3 py-2 text-sm">
          <input
            type="file"
            accept="application/json"
            className="hidden"
            onChange={(e) => onFile(e.target.files?.[0] ?? null)}
          />
          Upload report.json
        </label>
        {error ? <p className="text-sm text-rose-400">{error}</p> : null}

        {report ? (
          <div className="rounded-xl border border-zinc-800 bg-zinc-900/30 p-4">
            <p className="text-sm text-zinc-400">Dataset: {report.dataset_name}</p>
            <table className="mt-4 w-full text-left text-sm">
              <thead className="text-xs uppercase text-zinc-500">
                <tr>
                  <th className="py-2">Strategy</th>
                  <th>MRR</th>
                  <th>nDCG@10</th>
                  <th>Latency ms</th>
                </tr>
              </thead>
              <tbody>
                {ranked.map((row) => (
                  <tr key={row.strategy} className="border-t border-zinc-800">
                    <td className="py-2 font-medium text-zinc-200">{row.strategy}</td>
                    <td>{row.mrr_mean.toFixed(4)}</td>
                    <td>{(row.ndcg_at_k["10"] ?? 0).toFixed(4)}</td>
                    <td>{row.latency_ms_mean.toFixed(1)}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        ) : (
          <p className="text-sm text-zinc-500">
            Run an evaluation from the backend, then upload the generated <code>report.json</code> here.
          </p>
        )}
      </div>
    </div>
  );
}
